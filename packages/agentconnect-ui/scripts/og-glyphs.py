# Builds worker/og-glyphs.ts: the bitmaps worker/og-image.ts draws the approval
# link's preview with (the amount, the store and our label), so the worker can
# make a PNG without a font engine or an image library.
#
# Usage: python3 scripts/og-glyphs.py <Fustat[wght].ttf>
#   The font is Fustat (SIL Open Font License) from Google Fonts, the site's
#   own typeface. Needs Pillow. Rerun only to change the type or its sizes.

import base64, json, os, sys, zlib
from PIL import Image, ImageDraw, ImageFont

FACES = {
    # The amount: digits, currency symbols and codes.
    'amount': (140, 700, '0123456789.,-  $€£¥₹ABCDEFGHIJKLMNOPQRSTUVWXYZ'),
    # The store and the label: printable ASCII.
    'text': (44, 500, ''.join(chr(c) for c in range(32, 127)) + '€£¥₹'),
}

# The Polygon mark (public/logo-mark.svg), 26.823 x 24.096.
MARK = [(19.225, 0), (11.7, 4.322), (11.7, 17.812), (7.547, 20.219), (3.37, 17.81),
        (3.37, 12.994), (7.547, 10.608), (10.233, 12.166), (10.233, 8.27), (7.524, 6.731),
        (0, 11.102), (0, 19.749), (7.549, 24.096), (15.073, 19.749), (15.073, 6.261),
        (19.251, 3.852), (23.426, 6.261), (23.426, 11.055), (19.251, 13.486),
        (16.541, 11.914), (16.541, 15.791), (19.225, 17.34), (26.823, 13.017),
        (26.823, 4.322)]
MARK_H = 56

data = bytearray()
faces = {}
for name, (size, weight, chars) in FACES.items():
    font = ImageFont.truetype(sys.argv[1], size)
    font.set_variation_by_axes([weight])
    glyphs = {}
    for ch in dict.fromkeys(chars):
        x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')
        w, h = max(x1 - x0, 0), max(y1 - y0, 0)
        if w and h:
            img = Image.new('L', (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, fill=255, font=font, anchor='ls')
            glyphs[ch] = [len(data), w, h, x0, y0, round(font.getlength(ch))]
            data += img.tobytes()
        else:
            glyphs[ch] = [len(data), 0, 0, 0, 0, round(font.getlength(ch))]
    ascent, descent = font.getmetrics()
    faces[name] = {'size': size, 'ascent': ascent, 'descent': descent, 'glyphs': glyphs}

scale = MARK_H / 24.096
big = Image.new('L', (round(26.823 * scale * 4), MARK_H * 4), 0)
ImageDraw.Draw(big).polygon([(x * scale * 4, y * scale * 4) for x, y in MARK], fill=255)
mark = big.resize((big.width // 4, MARK_H), Image.LANCZOS)
faces['mark'] = [len(data), mark.width, mark.height]
data += mark.tobytes()

out = os.path.join(os.path.dirname(__file__), '..', 'worker', 'og-glyphs.ts')
with open(out, 'w') as f:
    f.write('// Generated by scripts/og-glyphs.py from Fustat (SIL Open Font License). Do not edit.\n')
    f.write('// Each glyph: [offset into BITMAPS, width, height, x from pen, y from baseline, advance].\n\n')
    f.write('type Glyph = [number, number, number, number, number, number];\n')
    f.write('export interface Face {\n  size: number;\n  ascent: number;\n  descent: number;\n  glyphs: Record<string, Glyph>;\n}\n\n')
    f.write('export const FACES: { amount: Face; text: Face; mark: [number, number, number] } = ' + json.dumps(faces, ensure_ascii=False, separators=(',', ':')) + ';\n\n')
    f.write('// 8-bit coverage, zlib-compressed.\n')
    f.write("export const BITMAPS = '" + base64.b64encode(zlib.compress(bytes(data), 9)).decode() + "';\n")
print(f'{len(data)} bytes of coverage, {os.path.getsize(out)} bytes written')
